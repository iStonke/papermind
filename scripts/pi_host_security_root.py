DIRECTORY = Path('/var/lib/papermind-security-20261012')
PLAN = DIRECTORY/'plan.json'
ENV = {'HOME':'/root','PATH':'/usr/sbin:/usr/bin:/sbin:/bin','LANG':'C',
    'DEBIAN_FRONTEND':'noninteractive','NEEDRESTART_MODE':'l'}
OPTIONS = ['--no-remove','--only-upgrade','--no-install-recommends']


def installed():
    return subprocess.check_output(['/usr/bin/dpkg-query','-W',
        '-f=${binary:Package}\t${Version}\t${db:Status-Abbrev}\n'],env=ENV,text=True)


def parse(output):
    assert not any(line.startswith('Remv ') for line in output.splitlines()), 'Removal forbidden'
    result=[]
    for line in output.splitlines():
        if not line.startswith('Inst '):continue
        match=re.fullmatch(r'Inst ([a-z0-9][a-z0-9+.:~-]*) \[([^\]]+)\] \((\S+).*',line)
        assert match is not None, 'Only installed packages may be upgraded'
        name,old,new=match.groups()
        assert re.fullmatch(r'[0-9][A-Za-z0-9.+:~_-]*',new), 'Version format differs'
        assert not name.startswith(('linux-','raspi','rpi-','docker','containerd','systemd','openssh')), 'System transition forbidden'
        result.append({'name':name,'old':old,'new':new})
    assert len(result)<=200, 'Plan bound'
    return sorted(result,key=lambda item:item['name'])


def apt(*args):
    result=subprocess.run(['/usr/bin/apt-get','-o','Acquire::Retries=3',
        '-o','DPkg::Lock::Timeout=30',*args],env=ENV,text=True,capture_output=True,timeout=1800)
    print(result.stdout,end='',flush=True)
    if result.returncode:
        print(result.stderr,end='',file=sys.stderr,flush=True)
        raise RuntimeError('APT failed')
    return result.stdout


def run(action):
    if action=='update':
        apt('update');return
    if action=='plan':
        metadata=installed()
        changes=parse(apt('--simulate',*OPTIONS,'install',*PACKAGES))
        value={'installed_sha256':hashlib.sha256(metadata.encode()).hexdigest(),'packages':changes}
        pending=PLAN.with_suffix('.tmp');pending.write_text(json.dumps(value));pending.chmod(0o600);pending.replace(PLAN)
        return
    value=json.loads(PLAN.read_text())
    assert hashlib.sha256(installed().encode()).hexdigest()==value['installed_sha256'], 'Installed packages changed'
    pins=[p['name']+'='+p['new'] for p in value['packages']]
    if not pins:return
    if action in {'verify','install'}:
        assert parse(apt('--simulate',*OPTIONS,'install',*pins))==value['packages'], 'APT plan changed'
    if action=='download':apt('-y','--download-only',*OPTIONS,'install',*pins)
    elif action=='install':apt('-y',*OPTIONS,'-o','Dpkg::Options::=--force-confold','install',*pins)


def main():
    assert os.getuid()==0, 'Root-owned helper requires root'
    assert len(sys.argv)==2 and sys.argv[1] in {'update','plan','download','verify','install'}, 'Fixed action required'
    assert len(PACKAGES)==103 and all(re.fullmatch(r'[a-z0-9][a-z0-9+.-]*',p) for p in PACKAGES)
    assert not DIRECTORY.is_symlink()
    DIRECTORY.mkdir(mode=0o700,exist_ok=True)
    assert DIRECTORY.stat().st_uid==0 and DIRECTORY.stat().st_mode&0o077==0
    with (DIRECTORY/'action.lock').open('a+') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
        run(sys.argv[1])


if __name__=='__main__':
    try:main()
    except Exception as exc:
        print(type(exc).__name__+': '+str(exc),file=sys.stderr);raise SystemExit(1)
